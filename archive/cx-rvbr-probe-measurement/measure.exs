{:ok, db} = CubDB.start_link(data_dir: "/tmp/cx-s37-probe/commits-copy", auto_compact: false)
t0 = System.monotonic_time(:millisecond)
count = CubDB.select(db) |> Enum.reduce(0, fn {_k, _v}, acc -> acc + 1 end)
t1 = System.monotonic_time(:millisecond)
IO.puts("ENTRIES=#{count}")
IO.puts("FULL_SELECT_EACH_MS=#{t1 - t0}")
IO.puts("EXCEEDS_5000MS=#{(t1 - t0) > 5000}")
sizes = CubDB.select(db) |> Enum.reduce([], fn {_k, v}, acc -> [:erlang.external_size(v) | acc] end) |> Enum.sort()
n = length(sizes)
IO.puts("VALUES=#{n}")
IO.puts("BYTES_TOTAL=#{Enum.sum(sizes)}")
IO.puts("MIN=#{List.first(sizes)} MEDIAN=#{Enum.at(sizes, div(n,2))} MAX=#{List.last(sizes)}")
IO.puts("P99=#{Enum.at(sizes, min(n-1, trunc(n*0.99)))}")
top = sizes |> Enum.reverse() |> Enum.take(10) |> Enum.sum()
IO.puts("TOP10_BYTES=#{top} PCT_OF_TOTAL=#{Float.round(top / Enum.sum(sizes) * 100, 2)}")
CubDB.stop(db)
